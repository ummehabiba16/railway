CREATE OR REPLACE PROCEDURE COMPLETE_BOOKING_BY_SM(P_INVOICEID IN VARCHAR2, P_NID IN VARCHAR2) IS
    V_BOOKINGID VARCHAR2(20);
BEGIN
    SELECT BOOKINGID INTO V_BOOKINGID
    FROM INVOICE 
    WHERE INVOICEID = P_INVOICEID;

    FOR R IN (SELECT TICKETID FROM TICKET WHERE BOOKINGID = V_BOOKINGID)
    LOOP
        UPDATE TICKET
        SET TICKETSTATUS = 'BOOKED'
        WHERE TICKETID = R.TICKETID;
    END LOOP;


    UPDATE BOOKING
    SET STATUS = 'SUCCESSFUL', SoldBy = 'S', NID = P_NID
    WHERE BOOKINGID = V_BOOKINGID;

END;
