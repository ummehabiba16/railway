CREATE OR REPLACE PROCEDURE Release_Tickets IS
BEGIN

    UPDATE BOOKING
    SET STATUS = 'FAILED'
    WHERE BOOKINGID IN (SELECT DISTINCT BOOKINGID FROM TICKET WHERE TICKETSTATUS = 'IN PROGRESS'
    AND BOOKINGHOLDUNTIL < CURRENT_TIMESTAMP);

    -- Step 2: Ban associated users for 5 minutes
    UPDATE USER_INFO
    SET BannedUntil = CAST(CURRENT_TIMESTAMP + INTERVAL '5' MINUTE AS TIMESTAMP)
    --SET BannedUntil = CURRENT_TIMESTAMP + INTERVAL '5' MINUTE
    WHERE UserId IN (
        SELECT DISTINCT b.UserId
        FROM BOOKING b
        JOIN TICKET t ON t.BookingId = b.BookingId
        WHERE t.TICKETSTATUS = 'IN PROGRESS'
          AND t.BOOKINGHOLDUNTIL < CURRENT_TIMESTAMP
    );

    -- Step 1: Release expired tickets
    UPDATE TICKET
    SET TICKETSTATUS = 'AVAILABLE'
    WHERE TICKETSTATUS = 'IN PROGRESS'
    AND BOOKINGHOLDUNTIL < CURRENT_TIMESTAMP;
    COMMIT;
END;
